export type CardStatus =
  'pending' | 'selected' | 'submitted' | 'confirmed' | 'locked' | 'outdated' | 'disabled';
export type CardKind = 'single' | 'multi' | 'image' | 'form' | 'review' | 'task' | 'result';
export type AgentField = {
  key: string;
  label: string;
  value: string;
  type?: 'text' | 'textarea' | 'number' | 'select';
  required?: boolean;
  options?: string[];
};
export type AgentOption = { id: string; title: string; description?: string; image?: string };
export type AgentCard = {
  id: string;
  kind: CardKind;
  title: string;
  module: string;
  status: CardStatus;
  version: number;
  fields: AgentField[];
  options: AgentOption[];
  selected: string[];
  min?: number;
  max?: number;
  expanded?: boolean;
  editing?: boolean;
  taskStatus?: '待执行' | '执行中' | '已完成' | '执行失败';
  progress?: number;
  dueAt?: number;
  executionVersion?: number;
  simulateFailure?: boolean;
  qa?: { label: string; status: '通过' | '警告' | '不通过' }[];
  acceptedWarnings?: boolean;
  jobIds?: string[];
  relatedCardIds?: string[];
  requiresAsset?: boolean;
  assetAttached?: boolean;
  customValue?: string;
  imageMediaId?: string;
  imageName?: string;
  editingContent?: boolean;
};
export type AgentMessage = {
  id: string;
  role: 'user' | 'assistant';
  text: string;
  cardIds: string[];
  createdAt: string;
};
export type AgentTask = {
  version: 1;
  flow?: 'intent-product-script';
  savedProductId?: string;
  activeCards?: Record<string, number>;
  id: string;
  sessionId: string;
  projectId: string;
  stage: string;
  revision: number;
  context: {
    style: string;
    audience: string;
    constraints: string[];
    product: Record<string, string>;
    request: string;
    referenceAssets?: { id: string; name: string; type: string; mediaId?: string }[];
    requestedHooks?: number;
    requestedCtas?: number;
    mainAngle?: string;
    testQuestion?: string;
    facts?: { confirmed: string[]; observable: string[]; unknown: string[]; prohibited: string[] };
    scripts?: { english: string; chinese: string; duration: string; ctas: string[] }[];
    storyboardRecords?: { shot: string; version: string; status: '通过' | '返工' | '无法判断'; reason: string }[];
    testData?: Record<string, string>;
  };
  messages: AgentMessage[];
  cards: AgentCard[];
  versions: { cardId: string; version: number; fields: AgentField[]; selected: string[]; at: string }[];
  confirmations: { cardId: string; version: number; at: string }[];
  pendingChange?: { module: string; instruction: string };
  demo: boolean;
  updatedAt: string;
  thinkingUntil?: number;
};
